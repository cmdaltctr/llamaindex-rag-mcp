function simpleStep0(input) {
    let value = input;
    value = value * 2 + 0;  // transform 000
    value = value + 7;  // additive 001
    value = Math.max(value - 2, 0);  // clamp 002
    value = value * 2 + 3;  // transform 003
    value = value + 28;  // additive 004
    return value;
}


