"""Experiment 33 corpus preparation (tasks 2.1-2.8).

Reads ``sources.json`` and, for every natural document:

1. downloads ``pdf_url`` into ``local_path`` when the file is missing;
2. verifies the recorded SHA-256 (a mismatch is a hard stop);
3. verifies the page count with poppler ``pdfinfo`` and the 100-page cap;
4. rejects any digest listed in ``dev_exclusions.json``.

It then regenerates ``SOURCING.md`` from ``sources.json``. pdf-inspector is
never called here.

    uv run python experiments/33-ocr-routing-natural-positive-2026-09-17/prepare_corpus.py
"""

from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
import urllib.request
from collections import Counter
from pathlib import Path

EXP_DIR = Path(__file__).resolve().parent
SOURCES = EXP_DIR / "sources.json"
EXCLUSIONS = EXP_DIR / "dev_exclusions.json"
SOURCING = EXP_DIR / "SOURCING.md"
MAX_PAGES = 100
USER_AGENT = "Mozilla/5.0 (experiment-33 corpus preparation)"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _download(url: str, dest: Path) -> None:
    if not url.startswith("https://"):
        raise SystemExit(f"{dest.name}: refusing non-https URL")
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})  # noqa: S310
    with urllib.request.urlopen(request, timeout=180) as response:  # noqa: S310 - https checked
        data = response.read()
    if not data.startswith(b"%PDF"):
        raise SystemExit(f"{dest.name}: download is not a PDF")
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(".pdf.tmp")
    tmp.write_bytes(data)
    tmp.replace(dest)


def _page_count(path: Path) -> int:
    info = subprocess.run(  # noqa: S603 - poppler is the intended binary
        ["pdfinfo", str(path)],  # noqa: S607
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    match = re.search(r"Pages:\s+(\d+)", info)
    return int(match.group(1)) if match else 0


def _verify(documents: list[dict], excluded: set[str]) -> list[str]:
    problems: list[str] = []
    for doc in documents:
        path = EXP_DIR / doc["local_path"]
        if not path.is_file():
            print(f"[prepare] {doc['doc_id']} downloading", flush=True)
            _download(doc["pdf_url"], path)
        if _sha256(path) != doc["sha256"]:
            problems.append(f"{doc['doc_id']}: SHA-256 differs from sources.json")
        pages = _page_count(path)
        if pages != doc["page_count"]:
            recorded = doc["page_count"]
            problems.append(f"{doc['doc_id']}: {pages} pages, sources.json says {recorded}")
        if pages > MAX_PAGES:
            problems.append(f"{doc['doc_id']}: {pages} pages exceeds the {MAX_PAGES}-page cap")
        if doc["sha256"] in excluded:
            problems.append(f"{doc['doc_id']}: digest is a development document")
    return problems


def _sourcing_markdown(sources: dict) -> str:
    documents = sources["documents"]
    selection = sources["selection"]
    counts = Counter(d["stratum"] for d in documents)
    lines = [
        "# Experiment 33 sourcing log",
        "",
        "Generated by `prepare_corpus.py` from `sources.json`. Do not edit by hand.",
        "",
        f"Selected {selection['date']}. {len(documents)} natural held-out documents, "
        f"{sum(d['page_count'] for d in documents)} pages.",
        "",
        "## Counts by stratum",
        "",
        "| Stratum | Documents | Pages |",
        "| --- | ---: | ---: |",
    ]
    for stratum, count in counts.items():
        pages = sum(d["page_count"] for d in documents if d["stratum"] == stratum)
        lines.append(f"| `{stratum}` | {count} | {pages} |")
    lines += ["", "## Selection procedure", ""]
    for stratum, text in selection["procedure"].items():
        lines.append(f"- **`{stratum}`**: {text}")
    lines += ["", f"pdf-inspector use: {selection['pdf_inspector_use']}.", "", "## Disclosures", ""]
    lines += [f"- {item}" for item in selection["disclosures"]]
    lines += [
        "",
        "## Documents",
        "",
        "| doc_id | Stratum | Title | Year | Pages | Licence | Source | SHA-256 |",
        "| --- | --- | --- | --- | ---: | --- | --- | --- |",
    ]
    for d in documents:
        title = str(d["title"]).replace("|", "/")[:80]
        lines.append(
            f"| `{d['doc_id']}` | `{d['stratum']}` | {title} | {d['year'] or ''} | "
            f"{d['page_count']} | {d['licence']} | "
            f"[{d['source_identifier']}]({d['landing_url']}) | "
            f"`{d['sha256'][:16]}…` |"
        )
    lines += ["", "Licence evidence per document is recorded in `sources.json`.", ""]
    return "\n".join(lines)


def main() -> int:
    """Download, verify and log the natural corpus."""
    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    excluded = set(json.loads(EXCLUSIONS.read_text(encoding="utf-8"))["digests"])
    problems = _verify(sources["documents"], excluded)
    if problems:
        for problem in problems:
            print(f"[prepare] FAIL {problem}", file=sys.stderr)
        return 1
    SOURCING.write_text(_sourcing_markdown(sources), encoding="utf-8")
    print(f"[prepare] {len(sources['documents'])} documents verified; SOURCING.md written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
