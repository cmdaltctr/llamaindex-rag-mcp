"""Guard: live files must not name the project's previous identity.

The project was renamed in ADR-092. This test scans every tracked file, and
every tracked file name, for the previous name in any case. A hit fails the
test unless the file, folder or text token sits in one of the named exemption
tables below. Each entry states why the old name has to stay.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parent.parent
#: The previous name. This file is the only live file that spells it.
_OLD_NAME = "om" + "rg"
_OLD = re.compile(_OLD_NAME, re.IGNORECASE)

#: Folders and files that record history. The scan never reads them.
_HISTORY_PREFIXES: dict[str, str] = {
    "docs/adr/": "ADRs keep the name the project had when they were written",
    "docs/tdr/": "TDRs keep the name the project had when they were written",
    "docs/04_tdr/": "TDRs keep the name the project had when they were written",
    "openspec/changes/archive/": "archived changes are history",
    "openspec/changes/experiment-42-clef-flash-confirmation/": "a run experiment, not yet archived",
    "CHANGELOG.md": "release history",
    "uv.lock": "generated by uv from pyproject.toml",
}

#: Files that must spell the old name.
_EXEMPT_FILES: dict[str, str] = {
    "tests/test_experiment_29_routing_repeat.py": "reads a file from the pinned commit afe151e",
    "openspec/specs/public-library-api/spec.md": "requires the old command to be absent",
    "openspec/specs/settings-file/spec.md": "requires the old folder not to be read",
    "openspec/specs/project-identity/spec.md": "requires the old names to be absent",
}


def _tracked_files() -> list[str]:
    """Return tracked paths, or skip when the tree is not a git checkout."""
    if not (_ROOT / ".git").exists():
        pytest.skip("not a git checkout")
    out = subprocess.run(
        ["git", "ls-files", "-z"],  # noqa: S607
        cwd=_ROOT,
        capture_output=True,
        check=True,
    ).stdout.decode("utf-8")
    return [p for p in out.split("\0") if p]


def _is_exempt_file(path: str) -> bool:
    return path in _EXEMPT_FILES


def _is_history(path: str) -> bool:
    # A numbered experiment folder is a run record. Its scripts keep the
    # names they ran with, apart from those the test suite still imports.
    if re.match(r"experiments/\d", path):
        return True
    return any(path == p or path.startswith(p) for p in _HISTORY_PREFIXES)


def _hits(path: str) -> list[str]:
    """Return the offence lines for one tracked path."""
    found: list[str] = []
    if _OLD.search(path):
        found.append("(file name)")
    full = _ROOT / path
    if not full.is_file():
        return found
    data = full.read_bytes()
    if b"\0" in data:
        return found
    for number, line in enumerate(data.decode("utf-8", "replace").splitlines(), start=1):
        if _OLD.search(line):
            found.append(f"{number}: {line.strip()[:90]}")
    return found


def test_live_files_do_not_name_the_old_identity() -> None:
    """No live file or file name names the old identity outside the exemption tables."""
    offenders: dict[str, list[str]] = {}
    for path in _tracked_files():
        if _is_history(path) or _is_exempt_file(path):
            continue
        hits = _hits(path)
        if hits:
            offenders[path] = hits
    if offenders:
        total = sum(len(v) for v in offenders.values())
        sample = [
            f"  {path}: {hits[0]}" + (f" (+{len(hits) - 1} more)" if len(hits) > 1 else "")
            for path, hits in sorted(offenders.items())[:40]
        ]
        pytest.fail(
            f"{total} hit(s) for the old name in {len(offenders)} file(s). "
            "Rename them, or add a named exemption with a reason.\n" + "\n".join(sample)
        )


def test_every_exemption_states_a_reason() -> None:
    """Each exemption entry carries a non-empty reason."""
    tables = (_HISTORY_PREFIXES, _EXEMPT_FILES)
    for table in tables:
        for name, reason in table.items():
            assert reason.strip(), f"exemption {name!r} has no reason"
