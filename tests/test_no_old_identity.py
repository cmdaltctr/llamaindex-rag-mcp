"""Guard: live files must not name the retired project identity.

The project was named OMRG until the ``rename-omrg-to-omrs`` change (ADR-092).
This test scans every tracked file, and every tracked file name, for the old
name in any case. A hit fails the test unless the file, folder or text token
sits in one of the named exemption tables below. Each entry states why the old
name has to stay (design D3, D6, D7, D9).

Add an exemption only when the text must describe the old identity. A new
feature that needs the old name for a different reason belongs in the table
with its own reason, not in a broader pattern.
"""

from __future__ import annotations

import fnmatch
import re
import subprocess
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parent.parent
_OLD = re.compile("omrg", re.IGNORECASE)

#: Folders and files that record history. The scan never reads them.
_HISTORY_PREFIXES: dict[str, str] = {
    "docs/adr/": "ADRs keep the name the project had when they were written",
    "docs/tdr/": "TDRs keep the name the project had when they were written",
    "docs/04_tdr/": "TDRs keep the name the project had when they were written",
    "openspec/changes/archive/": "archived changes are history",
    "openspec/changes/rename-omrg-to-omrs/": "this change describes the old identity",
    "CHANGELOG.md": "release history",
    "uv.lock": "generated by uv from pyproject.toml",
}

#: Files that must name the old identity because they detect or migrate it.
_EXEMPT_FILES: dict[str, str] = {
    "tests/test_no_old_identity.py": "this guard names the old identity",
    "src/omrs/config/legacy.py": "retired-variable tripwire keeps flat OMRG_ names (design D2)",
    "src/omrs/config/legacy_install.py": "startup check for an old install",
    "src/omrs/transports/cli/migrate.py": "the migrate command",
    "src/omrs/integrations/legacy_migration.py": "moves an old install to the new names",
    "docs/guides/migrating-from-omrg.md": "user migration guide",
    "openspec/specs/legacy-install-migration/spec.md": "contract about the old identity",
    "openspec/specs/project-identity/spec.md": "contract that lists the retired names",
    "openspec/specs/public-library-api/spec.md": "requires the omrg command to be absent",
    "openspec/specs/settings-file/spec.md": "describes the retired folder and file name",
}

#: File name patterns for the migration modules and their tests.
_EXEMPT_PATTERNS: dict[str, str] = {
    "tests/*test_legacy_install*.py": "tests for the startup check",
    "tests/*test_migrate*.py": "tests for the migrate command",
}

#: Text tokens removed from a line before the match.
_EXEMPT_TOKENS: dict[str, str] = {
    "omrg_dataset_epoch": "key stored inside existing LanceDB tables (design D3)",
    "omrg_task": "layout key stored in existing workspace.db pipelines (design D3)",
    "DATA/omrg": "large-data folder keeps its name (design D7)",
}


def _tracked_files() -> list[str]:
    """Return tracked paths, or skip when the tree is not a git checkout."""
    if not (_ROOT / ".git").exists():
        pytest.skip("not a git checkout")
    out = subprocess.run(
        ["git", "ls-files", "-z"],  # noqa: S607
        cwd=_ROOT,
        capture_output=True,
        check=True,
    ).stdout.decode("utf-8")
    return [p for p in out.split("\0") if p]


def _is_exempt_file(path: str) -> bool:
    if path in _EXEMPT_FILES:
        return True
    return any(fnmatch.fnmatch(path, pattern) for pattern in _EXEMPT_PATTERNS)


def _is_history(path: str) -> bool:
    # experiments/ is scanned for Python files only: reports and saved output are history.
    if path.startswith("experiments/") and not path.endswith(".py"):
        return True
    return any(path == p or path.startswith(p) for p in _HISTORY_PREFIXES)


def _strip_tokens(text: str) -> str:
    for token in _EXEMPT_TOKENS:
        text = text.replace(token, "")
    return text


def _hits(path: str) -> list[str]:
    """Return the offence lines for one tracked path."""
    found: list[str] = []
    if _OLD.search(_strip_tokens(path)):
        found.append("(file name)")
    full = _ROOT / path
    if not full.is_file():
        return found
    data = full.read_bytes()
    if b"\0" in data:
        return found
    for number, line in enumerate(data.decode("utf-8", "replace").splitlines(), start=1):
        if _OLD.search(_strip_tokens(line)):
            found.append(f"{number}: {line.strip()[:90]}")
    return found


def test_live_files_do_not_name_the_old_identity() -> None:
    """No live file or file name contains ``omrg`` outside the exemption tables."""
    offenders: dict[str, list[str]] = {}
    for path in _tracked_files():
        if _is_history(path) or _is_exempt_file(path):
            continue
        hits = _hits(path)
        if hits:
            offenders[path] = hits
    if offenders:
        total = sum(len(v) for v in offenders.values())
        sample = [
            f"  {path}: {hits[0]}" + (f" (+{len(hits) - 1} more)" if len(hits) > 1 else "")
            for path, hits in sorted(offenders.items())[:40]
        ]
        pytest.fail(
            f"{total} hit(s) for the old name in {len(offenders)} file(s). "
            "Rename them, or add a named exemption with a reason.\n" + "\n".join(sample)
        )


def test_every_exemption_states_a_reason() -> None:
    """Each exemption entry carries a non-empty reason."""
    tables = (_HISTORY_PREFIXES, _EXEMPT_FILES, _EXEMPT_PATTERNS, _EXEMPT_TOKENS)
    for table in tables:
        for name, reason in table.items():
            assert reason.strip(), f"exemption {name!r} has no reason"
